def token_path(data_dir: str) -> str:
    return os.path.join(data_dir, "config", "setup-token")


def ensure_token(data_dir: str) -> str:
    """The one-time setup token: kept across wizard restarts, deleted when setup ends."""
    path = token_path(data_dir)
    try:
        with open(path, encoding="utf-8") as fh:
            token = fh.read().strip()
        if token:
            return token
    except OSError:
        pass
    token = secrets.token_urlsafe(24)
    render.write_file(path, token + "\n")
    return token


def read_token(data_dir: str) -> str:
    try:
        with open(token_path(data_dir), encoding="utf-8") as fh:
            return fh.read().strip()
    except OSError:
        return ""


