class RateLimit:
    """At most ``limit`` failures in ``window`` seconds, for every client together
    (the wizard sits behind Caddy, so the client address is not reliable)."""

    def __init__(self, limit=5, window=60.0, clock=time.monotonic):
        self.limit, self.window, self.clock = limit, window, clock
        self.fails: list[float] = []
        self.lock = threading.Lock()

    def wait(self) -> int:
        """Seconds to wait before another attempt (0 = allowed)."""
        with self.lock:
            now = self.clock()
            self.fails = [t for t in self.fails if now - t < self.window]
            return int(self.window - (now - self.fails[0])) + 1 if len(self.fails) >= self.limit else 0

    def fail(self):
        with self.lock:
            self.fails.append(self.clock())


class Sessions:
    def __init__(self, clock=time.time):
        self.clock = clock
        self.items: dict[str, dict] = {}
        self.lock = threading.Lock()

    def new(self) -> tuple[str, dict]:
        with self.lock:
            now = self.clock()
            self.items = {k: v for k, v in self.items.items() if v["exp"] > now}
            if len(self.items) >= 50:  # drop the oldest
                self.items.pop(min(self.items, key=lambda k: self.items[k]["exp"]))
            sid = secrets.token_urlsafe(24)
            self.items[sid] = {"exp": now + SESSION_TTL, "csrf": secrets.token_urlsafe(24), "authed": False,
                               "data": {}}
            return sid, self.items[sid]

    def get(self, sid: str | None) -> dict | None:
        with self.lock:
            sess = self.items.get(sid or "")
            if sess and sess["exp"] > self.clock():
                return sess
            self.items.pop(sid or "", None)
            return None


