def _hs_env() -> dict:
    return {k: os.environ[k] for k in ("PATH", "HOME", "LANG", "TZ", "SSL_CERT_FILE") if k in os.environ}


def _hs(paths: dict, *args, timeout=30, stdin=None) -> tuple[int | None, str]:
    argv = [HEADSCALE_BIN, *args, "-c", paths["config"]]
    try:
        res = subprocess.run(argv, input=stdin, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                             timeout=timeout, env=_hs_env(), stdin=None if stdin is not None else subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return None, "timed out"
    except OSError as exc:
        return None, str(exc)
    return res.returncode, _strip(res.stdout)


def _strip(text: str) -> str:
    return re.sub(r"\x1b\[[0-9;]*[A-Za-z]", "", text or "").strip()


class Finisher:
    """Applies the collected settings. Idempotent: a retry never duplicates the
    API key, the Headscale user or the policy, and settings.json is written last."""

    def __init__(self, data_dir: str, env=None):
        self.data_dir = data_dir
        self.env = os.environ if env is None else env
        self.paths = render.paths(data_dir)

    def run(self, stored: dict, username: str):
        pending = self.paths["settings"] + ".pending"
        secret = ""
        try:
            with open(self.paths["settings"], encoding="utf-8") as fh:
                secret = json.load(fh).get("session_secret", "")
        except (OSError, ValueError, AttributeError):
            pass
        stored = dict(stored, session_secret=secret or secrets.token_urlsafe(48))
        render.write_file(pending, json.dumps(stored, indent=2, sort_keys=True) + "\n")
        try:
            settings = render.load_settings(self.env, pending)
            render.render_all(settings, self.data_dir)
        except ValueError as exc:
            raise SetupError(_("Invalid settings: {detail}", detail=str(exc))) from exc

        self.configure_headscale(settings, username)

        os.replace(pending, self.paths["settings"])
        os.chmod(self.paths["settings"], 0o600)
        try:
            os.unlink(token_path(self.data_dir))
        except OSError:
            pass

    def configure_headscale(self, settings: dict, username: str):
        """Run Headscale just long enough to create the API key, the admin's user and the policy."""
        os.makedirs(self.paths["hs_dir"], mode=0o700, exist_ok=True)
        proc = subprocess.Popen([HEADSCALE_BIN, "serve", "-c", self.paths["config"]], stdin=subprocess.DEVNULL,
                                stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, env=_hs_env())
        try:
            self.wait_healthy(proc)
            self.ensure_api_key()
            self.ensure_user(username)
            if settings.get("network_isolation", "true") == "true":
                self.ensure_policy()
        finally:
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()

    def wait_healthy(self, proc):
        deadline = time.monotonic() + HEADSCALE_START_TIMEOUT
        while time.monotonic() < deadline:
            if proc.poll() is not None:
                err = _strip((proc.stderr.read() or b"").decode(errors="replace"))[-600:]
                raise SetupError(_("Headscale stopped on start: {detail}", detail=err or proc.returncode))
            code, _out = _hs(self.paths, "health", timeout=5)
            if code == 0:
                return
            time.sleep(1)
        raise SetupError(_("Headscale did not become healthy in time."))

    def ensure_api_key(self):
        try:
            with open(self.paths["api_key"], encoding="utf-8") as fh:
                if fh.read().strip():
                    return
        except OSError:
            pass
        code, out = _hs(self.paths, "apikeys", "create", "--expiration", "90d")
        key = out.splitlines()[-1].strip() if out else ""
        if code != 0 or not key:
            raise SetupError(_("Could not create the Headscale API key: {detail}", detail=out or code))
        render.write_file(self.paths["api_key"], key + "\n")

    def ensure_user(self, username: str):
        code, out = _hs(self.paths, "users", "list", "-o", "json")
        names = set()
        if code == 0:
            try:
                names = {u.get("name") for u in json.loads(out) or []}
            except (ValueError, AttributeError):
                names = set()
        if username in names:
            return
        code, out = _hs(self.paths, "users", "create", username)
        if code != 0:
            raise SetupError(_("Could not create the Headscale user: {detail}", detail=out or code))

    def ensure_policy(self):
        code, _out = _hs(self.paths, "policy", "get")
        if code == 0:  # one exists: keep it
            return
        code, out = _hs(self.paths, "policy", "set", "-f", "/dev/stdin", stdin=ISOLATION_POLICY)
        if code != 0:
            raise SetupError(_("Could not apply the isolation policy: {detail}", detail=out or code))


